#!/usr/bin/env python3
"""The manual's examples as Forth tests (after 2068-Leap-C's tools/docexamples.py).

Every fenced ```forth block in docs/manual/*.md is a test: it becomes tests/doc/manual_<part>_<NN>.fs, a generated file
that ends with the part and line it comes from (last, so that the example's line numbers are the test's), and the
forth suite types it at the prompt (tools/forthtest.py: a line with `\\ expect: TEXT` must print TEXT, any other line
nothing). Each block starts from the booted machine, so a block defines what it uses. Text for reading only (a syntax
line, a fragment, what a screen shows) goes in a ```text block, which is not a test.

Usage: docexamples.py            regenerate tests/doc/manual_*.fs from the manual
       docexamples.py --check    fail if tests/doc/ differs from the manual (make check)"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "tests", "doc")
FOOTER = "\\ Generated by tools/docexamples.py from %s line %d: edit the manual, not this file.\n"


def examples():
    """{file name: text} of every ```forth block in the manual."""
    out = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "docs", "manual", "*.md"))):
        doc = os.path.relpath(path, ROOT)
        stem = "manual_" + re.sub(r"[^a-z0-9]+", "_", os.path.splitext(os.path.basename(path))[0].lower())
        lines = open(path, encoding="utf-8").read().split("\n")
        k, i = 0, 0
        while i < len(lines):
            if lines[i].strip() != "```forth":
                i += 1
                continue
            start = i + 1
            j = start
            while j < len(lines) and lines[j].strip() != "```":
                j += 1
            k += 1
            out["%s_%02d.fs" % (stem, k)] = "\n".join(lines[start:j]) + "\n" + FOOTER % (doc, start + 1)
            i = j + 1
    return out


def main():
    want = examples()
    have = {os.path.basename(p): open(p, encoding="latin-1").read()
            for p in glob.glob(os.path.join(OUT, "manual_*.fs"))}
    if "--check" in sys.argv:
        bad = sorted(n for n in set(want) | set(have) if want.get(n) != have.get(n))
        if bad:
            print("docexamples: tests/doc/ is out of date (%s); run tools/docexamples.py" % ", ".join(bad[:5]))
            sys.exit(1)
        print("docexamples: %d examples, tests/doc/ up to date" % len(want))
        return
    os.makedirs(OUT, exist_ok=True)
    for n in set(have) - set(want):
        os.remove(os.path.join(OUT, n))
    for n, text in want.items():
        if have.get(n) != text:
            with open(os.path.join(OUT, n), "w", encoding="latin-1") as f:
                f.write(text)
    print("docexamples: %d examples in tests/doc/" % len(want))


if __name__ == "__main__":
    main()
