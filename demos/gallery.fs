VARIABLE DG-CODE VARIABLE DG-COL VARIABLE DG-ROW
: DRAWGLYPH DG-ROW ! DG-COL ! DG-CODE !
2 0 DO DG-COL @ DG-ROW @ I + AT-XY DG-CODE @ EMIT DG-CODE @ EMIT LOOP ;
: ERASE2X2 DG-ROW ! DG-COL !
2 0 DO DG-COL @ DG-ROW @ I + AT-XY 32 EMIT 32 EMIT LOOP ;
VARIABLE TMPI VARIABLE TMPJ
: TC@ CELLS TCOL + @ ; : TC! CELLS TCOL + ! ;
: TD@ CELLS TDIR + @ ; : TD! CELLS TDIR + ! ;
: TS@ CELLS TSTEP + @ ; : TS! CELLS TSTEP + ! ;
: LN@ CELLS LANES + @ ;
: TR@ CELLS TLANE + @ LN@ ;
: SACTIVE@ CELLS SACTIVE + @ ; : SACTIVE! CELLS SACTIVE + ! ;
: SROW@ CELLS SROW + @ ; : SROW! CELLS SROW + ! ;
: SCOL@ CELLS SCOL + @ ; : SCOL! CELLS SCOL + ! ;
VARIABLE OV-SC VARIABLE OV-SR VARIABLE OV-TC VARIABLE OV-TR
: SET-OV OV-TR ! OV-TC ! OV-SR ! OV-SC ! ;
: ROW-OK? OV-SR @ OV-TR @ < INVERT OV-SR @ OV-TR @ 1+ > INVERT AND ;
: COL-OK? OV-SC @ OV-TC @ < INVERT OV-SC @ OV-TC @ 1+ > INVERT AND ;
: OVERLAPS? SET-OV ROW-OK? COL-OK? AND ;
: DRAW-BANDS
0 PAPER 7 INK 0 0 255 7 RECT
1000 0 DO LOOP
0 PAPER 0 INK 0 8 255 119 RECT
1000 0 DO LOOP
0 PAPER 6 INK 0 120 255 159 RECT
1000 0 DO LOOP
0 PAPER 4 INK 0 160 255 191 RECT
0 PAPER 0 INK ;
: REDRAW-HUD 7 PAPER 0 INK
0 0 AT-XY ." S:" SCORE @ .
10 0 AT-XY ." L:" LIVES @ .
16 0 AT-XY ." W:" WAVE @ .
0 PAPER 0 INK ;
: EXPLOSION-SOUND 7 239 SOUND 9 14 SOUND
6 2 SOUND 300 0 DO LOOP 6 8 SOUND 300 0 DO LOOP 6 16 SOUND 300 0 DO LOOP
9 0 SOUND ;
: WAVECLEAR-SOUND 10 0.08 BEEP 14 0.08 BEEP 17 0.08 BEEP 22 0.15 BEEP ;
: LIFELOST-SOUND -4 0.15 BEEP -9 0.25 BEEP ;
: GAMEOVER-SOUND -2 0.2 BEEP -6 0.2 BEEP -10 0.4 BEEP ;
: ERASE-TRUCK 6 PAPER 0 INK TRUCKCOL @ 17 ERASE2X2 ;
: SHOW-TRUCK 7 INK 6 PAPER
TRUCKDIR @ 0 = IF 144 ELSE 145 THEN TRUCKCOL @ 17 DRAWGLYPH ;
: TRUCK-LEFT ERASE-TRUCK
TRUCKCOL @ 0 > IF TRUCKCOL @ 1- TRUCKCOL ! THEN
TRUCKDIR @ 1 = 0= IF 1 TRUCKDIR ! THEN SHOW-TRUCK ;
: TRUCK-RIGHT ERASE-TRUCK
TRUCKCOL @ 30 < IF TRUCKCOL @ 1+ TRUCKCOL ! THEN
TRUCKDIR @ 0 = 0= IF 0 TRUCKDIR ! THEN SHOW-TRUCK ;
: TSHOW TMPI ! 2 INK 0 PAPER 146 TMPI @ TC@ TMPI @ TR@ DRAWGLYPH ;
: THIDE TMPI ! 0 PAPER 0 INK TMPI @ TC@ TMPI @ TR@ ERASE2X2 ;
: SPAWN-TARGET TMPI ! 1 TMPI @ TD! 0 TMPI @ TS! TMPI @ TSHOW ;
: INIT-TARGETS
0 0 CELLS TLANE + ! 1 1 CELLS TLANE + ! 2 2 CELLS TLANE + !
4 0 CELLS TCOL + ! 14 1 CELLS TCOL + ! 24 2 CELLS TCOL + !
0 SPAWN-TARGET 1 SPAWN-TARGET 2 SPAWN-TARGET ;
: SHIFT-LANE SWAP TMPI ! TMPI @ THIDE
TMPI @ CELLS TLANE + @ + 0 MAX 2 MIN TMPI @ CELLS TLANE + !
TMPI @ TSHOW ;
: MOVE-ONE-TARGET TMPI ! TMPI @ TS@ 1+ TMPI @ TS!
TMPI @ TS@ TSPEED @ < IF EXIT THEN 0 TMPI @ TS!
TMPI @ THIDE TMPI @ TC@ TMPI @ TD@ + TMPI @ TC!
TMPI @ TC@ 0 > INVERT IF 0 TMPI @ TC! 1 TMPI @ TD! THEN
TMPI @ TC@ 30 < INVERT IF 30 TMPI @ TC! -1 TMPI @ TD! THEN
TMPI @ TSHOW ;
: MOVE-TARGETS 0 MOVE-ONE-TARGET 1 MOVE-ONE-TARGET 2 MOVE-ONE-TARGET ;
: INIT-SHOTS 0 0 CELLS SACTIVE + ! 0 1 CELLS SACTIVE + ! 0 2 CELLS SACTIVE + ! ;
: FIND-FREE-SHOT
0 SACTIVE@ 0= IF 0 -1 EXIT THEN
1 SACTIVE@ 0= IF 1 -1 EXIT THEN
2 SACTIVE@ 0= IF 2 -1 EXIT THEN 0 0 ;
: FIRE FIRECD @ 0 > IF EXIT THEN
FIND-FREE-SHOT 0= IF DROP EXIT THEN TMPI !
1 TMPI @ SACTIVE! 14 TMPI @ SROW! TRUCKCOL @ TMPI @ SCOL!
7 INK 0 PAPER TRUCKCOL @ 14 AT-XY 42 EMIT
24 0.06 BEEP 3 FIRECD ! ;
: DO-HIT TMPJ ! TMPJ @ THIDE
STREAK @ 1+ STREAK ! SCORE @ 10 STREAK @ * + SCORE ! HITS @ 1+ HITS !
3 INK 0 PAPER TMPJ @ TC@ TMPJ @ TR@ AT-XY 147 EMIT 147 EMIT
300 0 DO LOOP EXPLOSION-SOUND 2 BORDER 200 0 DO LOOP 0 BORDER
31 RND TMPJ @ TC! TMPJ @ TSHOW 0 TMPI @ SACTIVE! REDRAW-HUD ;
: CHECK-HIT TMPI !
TMPI @ SCOL@ TMPI @ SROW@ 0 TC@ 0 TR@ OVERLAPS? IF 0 DO-HIT EXIT THEN
TMPI @ SCOL@ TMPI @ SROW@ 1 TC@ 1 TR@ OVERLAPS? IF 1 DO-HIT EXIT THEN
TMPI @ SCOL@ TMPI @ SROW@ 2 TC@ 2 TR@ OVERLAPS? IF 2 DO-HIT EXIT THEN ;
: MOVE-ONE-SHOT TMPI ! TMPI @ SACTIVE@ 0= IF EXIT THEN
0 PAPER 0 INK TMPI @ SCOL@ TMPI @ SROW@ AT-XY 32 EMIT
TMPI @ SROW@ 1- TMPI @ SROW!
TMPI @ SROW@ 1 < IF 0 TMPI @ SACTIVE! 0 STREAK ! -6 0.1 BEEP EXIT THEN
TMPI @ CHECK-HIT TMPI @ SACTIVE@ 0= IF EXIT THEN
7 INK 0 PAPER TMPI @ SCOL@ TMPI @ SROW@ AT-XY 42 EMIT ;
: MOVE-SHOTS 0 MOVE-ONE-SHOT 1 MOVE-ONE-SHOT 2 MOVE-ONE-SHOT ;
: NEW-WAVE WAVE @ 0 > IF WAVECLEAR-SOUND THEN
WAVE @ 1+ WAVE ! 5 WAVE @ 2 * + NEEDHITS ! 0 HITS !
150 WAVE @ 8 * - 60 MAX TIMERSTART ! TIMERSTART @ TIMER !
14 WAVE @ - 4 MAX TSPEED ! REDRAW-HUD ;
: LOSE-LIFE LIVES @ 1- LIVES ! LIFELOST-SOUND
1 BORDER 300 0 DO LOOP 0 BORDER
TIMERSTART @ TIMER ! 0 HITS ! REDRAW-HUD ;
: CHECK-WAVE-STATE HITS @ NEEDHITS @ < INVERT IF NEW-WAVE EXIT THEN
TIMER @ 1- TIMER ! TIMER @ 0 > INVERT IF LOSE-LIFE THEN ;
: HANDLE-KEY
KEYVAL @ 81 = KEYVAL @ 113 = OR IF 0 -1 SHIFT-LANE THEN
KEYVAL @ 65 = KEYVAL @ 97 = OR IF 0 1 SHIFT-LANE THEN
KEYVAL @ 87 = KEYVAL @ 119 = OR IF 1 -1 SHIFT-LANE THEN
KEYVAL @ 83 = KEYVAL @ 115 = OR IF 1 1 SHIFT-LANE THEN
KEYVAL @ 69 = KEYVAL @ 101 = OR IF 2 -1 SHIFT-LANE THEN
KEYVAL @ 68 = KEYVAL @ 100 = OR IF 2 1 SHIFT-LANE THEN
KEYVAL @ 79 = KEYVAL @ 111 = OR IF TRUCK-LEFT THEN
KEYVAL @ 80 = KEYVAL @ 112 = OR IF TRUCK-RIGHT THEN
KEYVAL @ 32 = IF FIRE THEN ;
: TICK KEY? IF KEY KEYVAL ! HANDLE-KEY THEN
MOVE-TARGETS MOVE-SHOTS
FIRECD @ 0 > IF FIRECD @ 1- FIRECD ! THEN
CHECK-WAVE-STATE 8000 0 DO LOOP ;
: GAME-LOOP BEGIN TICK LIVES @ 0 > WHILE REPEAT ;
: NEW-GAME 0 SCORE ! 3 LIVES ! 0 WAVE ! 0 STREAK ! 0 FIRECD !
DRAW-BANDS INIT-SHOTS
0 TRUCKDIR ! 16 TRUCKCOL ! SHOW-TRUCK
INIT-TARGETS NEW-WAVE REDRAW-HUD ;
