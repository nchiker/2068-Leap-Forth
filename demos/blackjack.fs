\ Blackjack for Leap-Forth: you against the dealer. Come
\ closer to 21 than the dealer without going over. Aces count
\ 1 or 11, J Q K 10; the dealer draws to 17. H hit, S stand.
\ Start word: BLACKJACK. As a cartridge: make blackjack
\ (CONTRIBUTING.md; the manual's Part 6).

\ The suits and the back of a card: UDGs 144 to 148
CREATE PIPS
24 C, 60 C, 126 C, 255 C, 255 C, 60 C, 24 C, 60 C,
102 C, 255 C, 255 C, 255 C, 126 C, 60 C, 24 C, 0 C,
24 C, 60 C, 126 C, 255 C, 255 C, 126 C, 60 C, 24 C,
24 C, 60 C, 24 C, 126 C, 255 C, 126 C, 24 C, 24 C,
204 C, 204 C, 51 C, 51 C, 204 C, 204 C, 51 C, 51 C,
: GLYPHS 40 0 DO PIPS I + C@ 0 UDG I + C! LOOP ;

\ Sound: noise for the shuffle, a click for each card
: WAIT ( n -- ) 0 DO LOOP ;
: SHUFFLE-SOUND 239 MIXER 1 10 VOLUME
  3 NOISE 900 WAIT 9 NOISE 900 WAIT
  2 NOISE 900 WAIT 12 NOISE 900 WAIT 1 0 VOLUME ;
: CARD-SOUND 1 60 TONE 253 MIXER 1 10 VOLUME
  700 WAIT 1 0 VOLUME ;
: KEY-BLIP 18 0.08 BEEP ;
: WIN-SOUND 8 0.1 BEEP 12 0.1 BEEP 15 0.15 BEEP ;
: LOSE-SOUND -3 0.15 BEEP -7 0.2 BEEP ;
: BUST-SOUND -4 0.12 BEEP -8 0.12 BEEP -12 0.3 BEEP ;
: BJ-SOUND 12 0.08 BEEP 15 0.08 BEEP 19 0.08 BEEP
  24 0.2 BEEP ;

\ The deck: card n (0-51) is rank n MOD 13 + 1, suit n / 13
52 ARRAY DECK  VARIABLE NEXT
: RANK ( n -- 1-13 ) 13 MOD 1+ ;
: SUIT ( n -- 0-3 ) 13 / ;
: SLOT ( i -- addr ) CELLS DECK + ;
: XCHG ( a1 a2 -- ) OVER @ OVER @ SWAP ROT ! SWAP ! ;
: SHUFFLE 52 0 DO I I SLOT ! LOOP
  0 51 DO I SLOT I 1+ RND SLOT XCHG -1 +LOOP 0 NEXT ! ;
: DEAL ( -- n ) NEXT @ DUP 1+ NEXT ! SLOT @ ;

\ A hand: cell 0 the number of cards, then the cards
12 ARRAY PLAYER  12 ARRAY DEALER
: CARD ( i hand -- n ) SWAP 1+ CELLS + @ ;
: ADD ( n hand -- ) DUP @ 1+ 2DUP SWAP ! CELLS + ! ;
: POINTS ( n -- p ) RANK DUP 10 > IF DROP 10 THEN
  DUP 1 = IF DROP 11 THEN ;
VARIABLE ACES
: SCORE ( hand -- total ) 0 ACES ! 0 SWAP DUP @ 0 DO
  I OVER CARD POINTS DUP 11 = IF ACES @ 1+ ACES ! THEN
  ROT + SWAP LOOP DROP
  BEGIN DUP 21 > ACES @ 0 > AND
  WHILE 10 - ACES @ 1- ACES ! REPEAT ;
: NATURAL? ( hand -- f ) DUP @ 2 = SWAP SCORE 21 = AND ;

\ A card is 4 by 4 cells, its corner at column CX, row CY
: FELT 0 INK 4 PAPER ;
VARIABLE CX  VARIABLE CY
VARIABLE X0  VARIABLE Y0  VARIABLE X1  VARIABLE Y1
: FACE ( c -- ) 4 0 DO CX @ CY @ I + AT-XY
  DUP EMIT DUP EMIT DUP EMIT DUP EMIT LOOP DROP ;
: OUTLINE 0 INK CX @ 8 * DUP X0 ! 31 + X1 !
  CY @ 8 * DUP Y0 ! 31 + Y1 !
  X0 @ Y0 @ X1 @ Y0 @ LINE  X0 @ Y1 @ X1 @ Y1 @ LINE
  X0 @ Y0 @ X0 @ Y1 @ LINE  X1 @ Y0 @ X1 @ Y1 @ LINE ;
: .RANK ( r -- ) DUP 1 = IF DROP ." A" EXIT THEN
  DUP 11 = IF DROP ." J" EXIT THEN
  DUP 12 = IF DROP ." Q" EXIT THEN
  DUP 13 = IF DROP ." K" EXIT THEN STR TYPE ;
: RED? ( n -- f ) SUIT DUP 1 = SWAP 2 = OR ;
: FACE-UP ( n -- ) 7 PAPER 0 INK 32 FACE
  DUP RED? IF 2 INK THEN CX @ 1+ CY @ 1+ AT-XY
  DUP RANK .RANK CX @ 1+ CY @ 2 + AT-XY
  SUIT 144 + EMIT OUTLINE ;
: FACE-DOWN 7 PAPER 2 INK 148 FACE OUTLINE ;

\ A hand of up to 8 cards is spread 4 columns apart; more
\ cards are pushed closer together, to fit 32 columns
VARIABLE HAND  VARIABLE HOLE
: COLUMN ( i n -- col ) DUP 8 > IF 1- 28 SWAP / ELSE
  DROP 4 THEN * ;
: SHOW ( hand row -- ) CY ! HAND ! FELT
  HAND @ @ 8 > IF 4 0 DO 0 CY @ I + AT-XY 32 SPACES LOOP
  THEN HAND @ @ 0 DO I HAND @ @ COLUMN CX !
  I 1 = HOLE @ AND HAND @ DEALER = AND
  IF FACE-DOWN ELSE I HAND @ CARD FACE-UP THEN
  LOOP FELT ;
: SHOW-DEALER DEALER 2 SHOW ;
: SHOW-PLAYER PLAYER 8 SHOW ;
: ROW ( row -- ) DUP 0 SWAP AT-XY 32 SPACES 0 SWAP AT-XY ;
: .DEALER 1 ROW ." DEALER"
  HOLE @ 0= IF ." : " DEALER SCORE . THEN ;
: .YOU 7 ROW ." YOU: " PLAYER SCORE . ;

\ The play
: GETKEY ( -- c ) KEY 32 OR ;
: DEAL-TO ( hand -- ) DEAL SWAP ADD CARD-SOUND ;
: OPENING 0 PLAYER ! 0 DEALER ! -1 HOLE !
  PLAYER DEAL-TO SHOW-PLAYER DEALER DEAL-TO SHOW-DEALER
  PLAYER DEAL-TO SHOW-PLAYER DEALER DEAL-TO SHOW-DEALER
  .DEALER .YOU ;
: HIT? ( -- f ) 14 ROW ." (H)IT OR (S)TAND?"
  BEGIN GETKEY DUP [CHAR] h = OVER [CHAR] s = OR 0=
  WHILE DROP REPEAT KEY-BLIP 14 ROW [CHAR] h = ;
: PLAYER-TURN BEGIN PLAYER SCORE 21 < IF HIT? ELSE 0 THEN
  WHILE PLAYER DEAL-TO SHOW-PLAYER .YOU REPEAT ;
: DEALER-TURN 0 HOLE ! SHOW-DEALER .DEALER
  BEGIN DEALER SCORE 17 < WHILE 4000 WAIT
  DEALER DEAL-TO SHOW-DEALER .DEALER REPEAT ;

\ OUTCOME: 1 you win, 2 the dealer wins, 3 bust,
\ 4 blackjack, 5 a push
VARIABLE OUTCOME
: JUDGE ( -- n ) PLAYER SCORE DEALER SCORE
  OVER 21 > IF 2DROP 3 EXIT THEN
  DUP 21 > IF 2DROP 1 EXIT THEN
  2DUP = IF 2DROP 5 EXIT THEN > IF 1 ELSE 2 THEN ;
: PLAY-HAND PLAYER NATURAL? IF DEALER NATURAL? IF 5 ELSE
  4 THEN EXIT THEN PLAYER-TURN
  PLAYER SCORE 21 > 0= IF DEALER-TURN THEN JUDGE ;
VARIABLE WON  VARIABLE LOST  VARIABLE PUSHED
: BUMP ( addr -- ) DUP @ 1+ SWAP ! ;
: TALLY ( n -- ) DUP 5 = IF PUSHED ELSE DUP 1 = OVER 4 = OR
  IF WON ELSE LOST THEN THEN BUMP DROP ;
: .TALLY 21 ROW ." WON " WON @ . ." LOST " LOST @ .
  ." PUSHED " PUSHED @ . ;
: RESULT ( n -- ) 16 ROW
  DUP 1 = IF ." YOU WIN!" 4 BORDER WIN-SOUND THEN
  DUP 2 = IF ." THE DEALER WINS" 1 BORDER LOSE-SOUND THEN
  DUP 3 = IF ." BUST! YOU LOSE" 2 BORDER BUST-SOUND THEN
  DUP 4 = IF ." BLACKJACK!" 3 BORDER BJ-SOUND THEN
  DUP 5 = IF ." A PUSH: NOBODY WINS" 5 BORDER THEN
  TALLY .TALLY ;
: TABLE FELT CLS 4 BORDER 11 0 AT-XY ." BLACKJACK" .TALLY ;
: ROUND SHUFFLE SHUFFLE-SOUND TABLE OPENING PLAY-HAND
  DUP OUTCOME ! 0 HOLE ! SHOW-DEALER .DEALER RESULT ;
: AGAIN? ( -- f ) 18 ROW ." ANOTHER ROUND? (Y/N)"
  BEGIN GETKEY DUP [CHAR] y = OVER [CHAR] n = OR 0=
  WHILE DROP REPEAT [CHAR] y = ;
: GAME 0 WON ! 0 LOST ! 0 PUSHED !
  BEGIN ROUND AGAIN? WHILE REPEAT
  0 INK 7 PAPER 7 BORDER CLS ." THANKS FOR PLAYING" CR ;

\ The start word: the title, then 0 RANDOMIZE after the key,
\ so that each game deals differently
: SUITS 0 INK 144 EMIT SPACE 2 INK 145 EMIT SPACE
  146 EMIT SPACE 0 INK 147 EMIT ;
: TITLE FELT CLS 4 BORDER 11 3 AT-XY ." BLACKJACK"
  12 5 AT-XY SUITS FELT
  2 8 AT-XY ." COME CLOSER TO 21 THAN THE"
  2 9 AT-XY ." DEALER WITHOUT GOING OVER."
  2 11 AT-XY ." ACES COUNT 1 OR 11, J Q K 10."
  2 12 AT-XY ." THE DEALER DRAWS TO 17."
  2 14 AT-XY ." H: HIT    S: STAND"
  2 18 AT-XY ." PRESS ANY KEY" KEY DROP ;
: BLACKJACK GLYPHS TITLE 0 RANDOMIZE GAME ;
